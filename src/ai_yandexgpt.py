from src.config import Config

class YandexGPTAI:
    def __init__(self):
        self.api_url = "https://llm.api.cloud.yandex.net/foundationModels/v1/completion"
        self.headers = {
            "Content-Type": "application/json",
            "Authorization": f"Api-Key {Config.YANDEX_API_KEY}",
            "x-folder-id": Config.YANDEX_FOLDER_ID
        }
        self.model = "yandexgpt-lite"
        self.max_retries = 2
        logging.info("✅ YandexGPT AI configured")
    
    def generate_travel_plan(self, user_data):
        """Генерация детального плана путешествия через YandexGPT"""
        prompt = self._build_detailed_prompt(user_data)
        
        for attempt in range(self.max_retries):
            try:
                response = self._make_api_request(prompt)
                if response:
                    # Проверяем качество ответа
                    quality_score = self._get_response_quality_score(response)
                    
                    if quality_score >= 7 or attempt == self.max_retries - 1:
                        return response
                    else:
                        logging.info(f"🔄 Ответ недостаточно детальный (оценка: {quality_score}/10), пробуем снова...")
                        # Улучшаем промпт для повторного запроса
                        prompt = self._build_enhanced_prompt(user_data, response)
                else:
                    if attempt == self.max_retries - 1:
                        return self._get_detailed_fallback_response(user_data)
                        
            except Exception as e:
                logging.error(f"❌ YandexGPT API error (attempt {attempt + 1}): {e}")
                if attempt == self.max_retries - 1:
                    return self._get_detailed_fallback_response(user_data)
        
        return self._get_detailed_fallback_response(user_data)
    
    def _make_api_request(self, prompt):
        """Отправка запроса к YandexGPT API"""
        data = {
            "modelUri": f"gpt://{Config.YANDEX_FOLDER_ID}/{self.model}",
            "completionOptions": {
                "stream": False,
                "temperature": 0.7,
                "maxTokens": 4000  # Увеличили для детальных ответов
            },
            "messages": [
                {
                    "role": "system",
                    "text": """Ты - эксперт по путешествиям с 15-летним опытом работы гидом. 
Твоя задача - создавать максимально детальные, практичные и персонализированные планы путешествий.
Ты должен предоставлять КОНКРЕТНУЮ информацию: реальные названия мест, точные цены, детальные маршруты.
Используй смайлики для наглядности и структурируй информацию для легкого чтения."""
                },
                {
                    "role": "user", 
                    "text": prompt
                }
            ]
        }
        
        try:
            response = requests.post(
                self.api_url,
                headers=self.headers,
                json=data,
                timeout=45  # Увеличили таймаут для сложных запросов
            )
            
            if response.status_code == 200:
                result = response.json()
                return result['result']['alternatives'][0]['message']['text']
            else:
                logging.error(f"YandexGPT API error: {response.status_code} - {response.text}")
                return None
                
        except requests.exceptions.Timeout:
            logging.error("YandexGPT API timeout")
            return None
        except Exception as e:
            logging.error(f"YandexGPT API request failed: {e}")
            return None
    
