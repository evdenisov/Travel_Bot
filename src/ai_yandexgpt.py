    def _get_response_quality_score(self, response):
        """Оцениваем качество ответа по детализации"""
        if not response:
            return 0
            
        score = 0
        
        # Критерии оценки детализации
        criteria = {
            'length': len(response) > 2500,
            'prices': 'руб' in response.lower(),
            'schedule': '⏰' in response,
            'hotels': '🏨' in response and any(word in response.lower() for word in ['отель', 'хостел', 'апартамент']),
            'food': '🍽️' in response and any(word in response.lower() for word in ['ресторан', 'кафе', 'столовая']),
            'transport': '🚇' in response and any(word in response.lower() for word in ['такси', 'метро', 'автобус']),
            'tips': '💡' in response,
            'budget': '💰' in response and any(word in response.lower() for word in ['бюджет', 'расход', 'стоимость']),
            'lists': response.count('•') > 15,
            'times': response.count('⏰') > 3
        }
        
        score = sum(2 if value else 0 for value in criteria.values())
        
        # Дополнительные баллы за очень детальные ответы
        if len(response) > 4000:
            score += 2
        if response.count('•') > 25:
            score += 2
            
        return min(score, 10)
    
